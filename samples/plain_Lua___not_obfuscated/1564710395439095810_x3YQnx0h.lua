local espGeneratorsActive = false
local generatorProgConns = {}

local function espAttachGenerator(obj, tag, color)
    if not obj or not obj.Parent then return end
    
    pcall(function()
        local oldHl = obj:FindFirstChild(tag)
        local oldBb = obj:FindFirstChild(tag .. "_bb")
        if oldHl then oldHl:Destroy() end
        if oldBb then oldBb:Destroy() end
    end)
    
    if generatorProgConns[obj] then 
        pcall(function() generatorProgConns[obj]:Disconnect() end)
        generatorProgConns[obj] = nil 
    end

    local root = obj.PrimaryPart or obj:FindFirstChild("Base") or obj:FindFirstChild("Main")
    if not root then
        for _, child in ipairs(obj:GetChildren()) do
            if child:IsA("BasePart") then root = child; break end
        end
    end
    if not root and obj:IsA("BasePart") then root = obj end
    if not root then return end

    pcall(function()
        local hl = Instance.new("Highlight")
        hl.Name = tag
        hl.FillColor = color
        hl.FillTransparency = 0.6
        hl.OutlineColor = color
        hl.OutlineTransparency = 0
        hl.DepthMode = Enum.HighlightDepthMode.AlwaysOnTop
        hl.Adornee = obj
        hl.Parent = obj

        local bb = Instance.new("BillboardGui")
        bb.Name = tag .. "_bb"
        bb.Adornee = root
        bb.Size = UDim2.new(0, 100, 0, 20)
        bb.StudsOffset = Vector3.new(0, 3.8, 0)
        bb.AlwaysOnTop = true
        bb.MaxDistance = 1000
        bb.Parent = obj

        local lbl = Instance.new("TextLabel")
        lbl.Size = UDim2.new(1, 0, 1, 0)
        lbl.BackgroundTransparency = 1
        lbl.TextColor3 = color
        lbl.TextStrokeTransparency = 0.5
        lbl.TextStrokeColor3 = Color3.new(0, 0, 0)
        lbl.TextSize = 15
        lbl.Font = Enum.Font.SourceSansBold
        lbl.Parent = bb

        local prog = obj:FindFirstChild("Progress")
        if prog and prog:IsA("NumberValue") then
            lbl.Text = "Generator (" .. math.floor(prog.Value) .. "%)"
            local c = prog.Changed:Connect(function()
                if lbl.Parent then 
                    lbl.Text = "Generator (" .. math.floor(prog.Value) .. "%)" 
                end
            end)
            generatorProgConns[obj] = c
        else
            lbl.Text = ""
        end
    end)
end

local function espDetachGenerator(obj, tag)
    if not obj then return end
    if generatorProgConns[obj] then 
        pcall(function() generatorProgConns[obj]:Disconnect() end)
        generatorProgConns[obj] = nil 
    end
    pcall(function()
        local h = obj:FindFirstChild(tag); if h then h:Destroy() end
        local b = obj:FindFirstChild(tag .. "_bb"); if b then b:Destroy() end
    end)
end

local function espDoGenerators(on)
    for _, obj in ipairs(Workspace:GetDescendants()) do
        if obj.Name == "Generator" then
            if on then 
                espAttachGenerator(obj, "esp_g", Color3.fromRGB(255, 255, 0))
            else 
                espDetachGenerator(obj, "esp_g") 
            end
        end
    end
end

