local espEnabledMedkit = false
local espEnabledBloxy = false

local itemHighlights = {
    Medkit = {},
    BloxyCola = {}
}

local function applyItemHighlight(item)
    if not (item:IsA("BasePart") or item:IsA("Model")) then return end
    
    local name = item.Name
    if (name ~= "Medkit" and name ~= "BloxyCola") then return end

    local isMedkit = (name == "Medkit" and espEnabledMedkit)
    local isBloxy = (name == "BloxyCola" and espEnabledBloxy)

    if not (isMedkit or isBloxy) then return end

    local targetPart = item:IsA("BasePart") and item or item:FindFirstChildWhichIsA("BasePart")
    if not targetPart or targetPart:FindFirstChild("ItemHighlight") then return end

    local highlight = Instance.new("Highlight")
    highlight.Name = "ItemHighlight"
    highlight.Adornee = item
    highlight.FillTransparency = 0.5
    highlight.OutlineTransparency = 0
    highlight.DepthMode = Enum.HighlightDepthMode.AlwaysOnTop

    if isMedkit then
        highlight.FillColor = Color3.fromRGB(255, 105, 180)
        highlight.OutlineColor = Color3.fromRGB(255, 105, 180)
        table.insert(itemHighlights.Medkit, highlight)
    elseif isBloxy then
        highlight.FillColor = Color3.fromRGB(0, 150, 255)
        highlight.OutlineColor = Color3.fromRGB(0, 150, 255)
        table.insert(itemHighlights.BloxyCola, highlight)
    end

    highlight.Parent = targetPart
end

local function clearItemESP(itemName)
    for _, highlight in ipairs(itemHighlights[itemName]) do
        if highlight and highlight.Parent then
            highlight:Destroy()
        end
    end
    itemHighlights[itemName] = {}
end

local function scanExistingItems(itemName)
    clearItemESP(itemName)
    for _, item in ipairs(Workspace:GetDescendants()) do
        if item.Name == itemName then
            applyItemHighlight(item)
        end
    end
end

