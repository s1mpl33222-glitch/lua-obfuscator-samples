local string_find = string.find
local string_sub = string.sub
local pairs = pairs
local ipairs = ipairs

local EnglishKeyCache = {}
for lang, dict in pairs(Translations) do
    for key, val in pairs(dict) do
        EnglishKeyCache[val] = key
    end
end

local function GetEnglishKey(value)
    return EnglishKeyCache[value] or value
end

local TranslationModule = {}

function TranslationModule.Translate(gui, lang)
    if not gui then return end
    local dict = Translations[lang]
    local elements = gui:GetDescendants()
    for i = 1, #elements do
        local element = elements[i]
        if element:IsA("TextLabel") or element:IsA("TextButton") then
            local currentText = element.Text
            local original = element:GetAttribute("OriginalText")
            if not original and Translations["PT"][currentText] then
                original = currentText
                element:SetAttribute("OriginalText", original)
            end
            if original then
                if lang == "EN" then
                    local splitPos = string_find(currentText, ": ")
                    if splitPos then
                        local val = string_sub(currentText, splitPos + 2)
                        element.Text = original .. ": " .. GetEnglishKey(val)
                    else
                        element.Text = original
                    end
                elseif dict then
                    local translatedText = dict[original]
                    if translatedText then
                        local splitPos = string_find(currentText, ": ")
                        if splitPos then
                            local val = string_sub(currentText, splitPos + 2)
                            element.Text = translatedText .. ": " .. (dict[val] or val)
                        else
                            element.Text = translatedText
                        end
                    end
                end
            end
        end
    end
end

return TranslationModule
