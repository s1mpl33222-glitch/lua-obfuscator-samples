--==================================================

local function SubmitKey(key, fromSavedKey)
    if Checking then
        return
    end

    key = Trim(key)
    if key == "" then
        SetStatus("Enter your key first.", "error")
        return
    end

    if not IsCurrentRouteSupported() then
        SetStatus("Unsupported game • no JNKIE route found.", "error")
        GameSupported.Text = "Unsupported"
        GameSupported.TextColor3 = THEME.error
        return
    end

    Checking = true
    VerifyButton.Text = "Loading..."
    SetStatus(
        fromSavedKey and "Using saved key • loading..."
            or "Loading routed script...",
        "loading"
    )

    -- Preserve Remember Key / auto-login behavior, but DO NOT perform a
    -- separate public JNKIE validation request here.
    if RememberKey then
        SaveKey(key)
    elseif not fromSavedKey then
        DeleteSavedKey()
    end

    HandOffToJnkie(key)
end

