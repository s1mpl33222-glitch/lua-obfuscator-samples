UpdateToggle()
SetStatus("Ready", "normal")

task.spawn(function()
    task.wait(0.5)

    -- Unsupported games should never touch a saved key.
    if not IsCurrentRouteSupported() then
        return
    end

    local savedKey = ReadSavedKey()
    if not savedKey then
        return
    end

    KeyBox.Text = savedKey
    SetStatus("Checking saved key...", "loading")

    local valid, reason = ValidateSavedKeyForAutoLogin(savedKey)

    if valid == false then
        -- Any key JNKIE now rejects is stale for auto-login. Delete it before
        -- the protected loader sees it so an old/expired key cannot disconnect
        -- the user every time Rift starts.
        DeleteSavedKey()
        KeyBox.Text = ""
        SetStatus("Old / expired saved key removed. Enter a new key.", "error")
        warn("[RIFT] Removed invalid saved key:", reason)
        return
    end

    if valid == nil then
        -- A network/SDK outage is NOT proof that the key is expired.
        -- Keep the file, but do not auto-submit it and risk a disconnect.
        SetStatus("Couldn't verify saved key. Submit manually or get a new key.", "warning")
        warn("[RIFT] Saved-key validation unavailable:", reason)
        return
    end

    SetStatus("Saved key valid • auto login...", "success")
    task.wait(0.20)
    SubmitKey(savedKey, true)
end)

