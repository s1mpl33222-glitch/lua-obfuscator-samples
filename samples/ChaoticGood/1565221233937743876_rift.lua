local function RequestWithTimeout(requestFunction, options, timeoutSeconds)
    local done = false
    local ok, response
    task.spawn(function()
        ok, response = pcall(requestFunction, options)
        done = true
    end)
    local started = os.clock()
    repeat
        task.wait()
    until done or os.clock() - started > (timeoutSeconds or 15)
    if not done then
        return false, nil, "Request timed out"
    end
    if not ok then
        return false, nil, tostring(response)
    end
    return true, response, nil
end

local function GetRoutedScriptHash()
    -- JNKIE declares S and i before the custom Key UI. S[i] is the
    -- protected script selected by the current PlaceId / GameId route.
    local ok, routedScriptHash = pcall(function()
        if type(S) ~= "table" or i == nil then
            return nil
        end
        return S[i]
    end)

    if not ok or type(routedScriptHash) ~= "string" or routedScriptHash == "" then
        return nil
    end

    return routedScriptHash
end

local function IsCurrentRouteSupported()
    return GetRoutedScriptHash() ~= nil
end

local function ValidateRoutedKey(key)
    -- IMPORTANT:
    -- Do NOT call Junkie.check_key() here.
    --
    -- JNKIE's current Inline UI documentation recommends passing the submitted
    -- key directly to the protected loader, especially for one-time keys.
    -- A separate check_key() call can record first use / consume a one-time key
    -- before the protected routed loader gets to authenticate it.
    --
    -- This UI only checks that JNKIE resolved a route. The generated loader
    -- performs the real/final authentication and protected script delivery.
    key = Trim(key)

    if key == "" then
        return false, "EMPTY", "No key entered."
    end

    if not IsCurrentRouteSupported() then
        return false, "NO_ROUTE", "Unable to resolve the routed script."
    end

    return true, "HANDOFF", nil
end

