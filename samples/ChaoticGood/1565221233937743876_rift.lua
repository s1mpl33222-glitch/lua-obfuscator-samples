        local inviteCode = url:match("discord%.com/invite/([^/%?]+)") or url:match("discord%.gg/([^/%?]+)")
        if inviteCode then
            local success = pcall(function()
                requestFunction({
                    Url = "http://127.0.0.1:6463/rpc?v=1",
                    Method = "POST",
                    Headers = {
                        ["Content-Type"] = "application/json",
                        ["Origin"] = "https://discord.com"
