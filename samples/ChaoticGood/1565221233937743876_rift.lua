                    Body = HttpService:JSONEncode({
                        cmd = "INVITE_BROWSER",
                        args = { code = inviteCode },
                        nonce = tostring(math.random(100000000, 999999999))
                    })
                })
            end)
            if success then
                return true
            end
        end
    end
    return false
end

