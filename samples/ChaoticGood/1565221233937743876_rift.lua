        return false
    end
    if isfile then
        local success, exists = pcall(function()
            return isfile(CONFIG.KeyFile)
        end)
        if success and not exists then
            return true
        end
    end
    return pcall(function()
        delfile(CONFIG.KeyFile)
    end)
end

local SavedKeySDK = nil

local function GetSavedKeySDK()
    if SavedKeySDK then
        return SavedKeySDK
    end

    if typeof(loadstring) ~= "function" then
        return nil, "loadstring unavailable"
    end

    local ok, source = pcall(function()
        return game:HttpGet("https://jnkie.com/sdk/library.lua")
    end)
    if not ok or typeof(source) ~= "string" or source == "" then
        return nil, "could not download JNKIE SDK"
    end

    local chunk, compileError = loadstring(source, "@Rift/SavedKeyGuard")
    if not chunk then
        return nil, tostring(compileError or "SDK compile failed")
    end

    local ran, sdk = pcall(chunk)
    if not ran or typeof(sdk) ~= "table" then
        return nil, tostring(sdk or "SDK initialization failed")
    end

    sdk.service = CONFIG.Service
    sdk.identifier = CONFIG.Identifier

    SavedKeySDK = sdk
    return sdk
end

local function ValidateSavedKeyForAutoLogin(key)
    key = Trim(key)
    if key == "" then
        return false, "EMPTY"
    end

    local sdk, sdkError = GetSavedKeySDK()
    if not sdk then
        return nil, "SDK:" .. tostring(sdkError)
    end

    -- IMPORTANT:
    -- check_key() is used ONLY for a key that is already saved from an older
    -- session. Fresh/manual keys still use direct protected-loader handoff.
    local ok, result = pcall(sdk.check_key, key)
    if not ok then
        return nil, "REQUEST:" .. tostring(result)
    end

    if typeof(result) ~= "table" or typeof(result.valid) ~= "boolean" then
        return nil, "BAD_RESPONSE"
    end

    if result.valid == true then
        return true, tostring(result.message or "KEY_VALID")
    end

    return false, tostring(result.error or "KEY_INVALID")
end

