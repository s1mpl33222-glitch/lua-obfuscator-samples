/* ---------------------------------------------------------------------------
   Oblivion / oblivion.menu

   One screen. Not a short page, not a page that happens to fit: the document
   is exactly the height of the viewport and does not scroll at all.

   Which leaves a problem, because a script hub still has to show what is in it
   and what it costs, and there is nowhere below the fold to put either. The
   answer is the one the product itself uses. Oblivion is a menu that opens over
   a game you are already in; this page is a menu that opens over a page you are
   already on. The two buttons in the middle open panels in place, they grow
   from 0.97 with the same shadow the real window has, the ground behind them
   dims, and nothing ever moves the page. Everything is one keypress from where
   you started.

   The ground is a violet silk: a fixed WebGL canvas running domain-warped value
   noise, a radial vignette over it, and film grain inside the shader so the
   large flat areas do not band. The noise is written here rather than lifted
   from anywhere; the technique is the ordinary one, fBm with the sample point
   displaced by more fBm, with each octave rotated so it does not line up with
   its own axes, which is the thing that otherwise gives value noise away.

   The menu panel is in the menu's own Oblivion theme, straight out of the
