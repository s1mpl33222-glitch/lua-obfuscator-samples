<script>
(function () {
  "use strict";
  var still = matchMedia("(prefers-reduced-motion: reduce)").matches;

  /* --- the ground -------------------------------------------------------
     Domain-warped fBm: noise sampled at a position that is itself displaced by
     noise, which is what makes a field look like it is flowing rather than
     merely wobbling. Each octave is rotated before it is added, because value
     noise lines up with its own axes and a stack of unrotated octaves shows a
     grid in the flat areas.

     Rendered at 60% of the viewport and capped to 30 frames a second. It is a
     slow low-frequency field; nobody can see either economy, and both of them
     matter on the hardware that runs Roblox.

     Any failure at all leaves the canvas hidden and the CSS gradient underneath
     showing through, which is the same picture standing still.
  --------------------------------------------------------------------- */
  (function ground() {
    var canvas = document.getElementById("silk");
    var gl = canvas.getContext("webgl", { alpha: false, antialias: false, depth: false,
                                          stencil: false, powerPreference: "low-power" });
    if (!gl) { canvas.style.display = "none"; return; }

    var VERT = "attribute vec2 p;void main(){gl_Position=vec4(p,0.,1.);}";
    var FRAG = [
      // Not every mobile GPU has highp in a fragment shader, and asking for one
      // it lacks fails the compile, which would drop the ground on exactly the
      // devices this is for.
      "#ifdef GL_FRAGMENT_PRECISION_HIGH",
      "precision highp float;",
      "#else",
      "precision mediump float;",
      "#endif",
      "uniform vec2 uR;uniform float uT;",
      "uniform vec3 uDeep;uniform vec3 uMid;uniform vec3 uLit;",
      "float h(vec2 p){return fract(sin(dot(p,vec2(127.1,311.7)))*43758.5453123);}",
      "float n(vec2 p){vec2 i=floor(p),f=fract(p);vec2 u=f*f*f*(f*(f*6.-15.)+10.);",
      " return mix(mix(h(i),h(i+vec2(1,0)),u.x),mix(h(i+vec2(0,1)),h(i+vec2(1,1)),u.x),u.y);}",
      // 0.5 radians per octave. Any angle that is not a multiple of a quarter
      // turn works; this one just looks the least regular.
      "const mat2 R=mat2(0.8776,-0.4794,0.4794,0.8776);",
      "float fbm(vec2 p){float v=0.,a=.5;for(int i=0;i<5;i++){v+=a*n(p);p=R*p*2.02;a*=.5;}return v;}",
      "void main(){",
      " vec2 uv=(gl_FragCoord.xy-.5*uR)/min(uR.x,uR.y);",
      " float t=uT*.035;",
      " vec2 q=vec2(fbm(uv*1.4+t),fbm(uv*1.4-t+5.2));",
      " vec2 w=uv*1.3+.62*q;",
      " float a=fbm(w*1.1+vec2(0.,t*1.4));",
      " float b=fbm(w*2.1-vec2(t*.9,0.)+9.);",
      " float f=a*.66+b*.34;",
      " float lum=clamp(.5+f*.62,0.,1.);",
      " float glow=smoothstep(1.15,0.,length(uv));",
      " vec3 col=mix(uDeep,uMid,smoothstep(.14,.6,lum));",
      " col=mix(col,uLit,smoothstep(.6,1.,lum)*(.45+.55*glow));",
      // Grain, in the shader rather than as an overlay, so it lands before the
      // colour is quantised and the wide flat areas do not band.
      " col+=(fract(sin(dot(gl_FragCoord.xy,vec2(12.9898,78.233))+uT)*43758.5453)-.5)*.016;",
      " gl_FragColor=vec4(col,1.);",
      "}"
    ].join("\n");

    function build(kind, src) {
      var s = gl.createShader(kind);
      gl.shaderSource(s, src); gl.compileShader(s);
      return gl.getShaderParameter(s, gl.COMPILE_STATUS) ? s : null;
    }
    var v = build(gl.VERTEX_SHADER, VERT), f = build(gl.FRAGMENT_SHADER, FRAG);
    if (!v || !f) { canvas.style.display = "none"; return; }

    var prog = gl.createProgram();
    gl.attachShader(prog, v); gl.attachShader(prog, f); gl.linkProgram(prog);
    if (!gl.getProgramParameter(prog, gl.LINK_STATUS)) { canvas.style.display = "none"; return; }
    gl.useProgram(prog);

    gl.bindBuffer(gl.ARRAY_BUFFER, gl.createBuffer());
    gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1, -1, 3, -1, -1, 3]), gl.STATIC_DRAW);
    var loc = gl.getAttribLocation(prog, "p");
    gl.enableVertexAttribArray(loc);
    gl.vertexAttribPointer(loc, 2, gl.FLOAT, false, 0, 0);

    function rgb(name) {
      var hex = getComputedStyle(document.documentElement).getPropertyValue(name).trim();
      var k = parseInt(hex.slice(1), 16);
      return [(k >> 16 & 255) / 255, (k >> 8 & 255) / 255, (k & 255) / 255];
    }
    gl.uniform3fv(gl.getUniformLocation(prog, "uDeep"), rgb("--deep"));
    gl.uniform3fv(gl.getUniformLocation(prog, "uMid"), [0.42, 0.19, 0.84]);
    gl.uniform3fv(gl.getUniformLocation(prog, "uLit"), rgb("--lit"));

    var uR = gl.getUniformLocation(prog, "uR");
    var uT = gl.getUniformLocation(prog, "uT");
    var lost = false;
    canvas.addEventListener("webglcontextlost", function (e) { e.preventDefault(); lost = true; canvas.style.display = "none"; });

    function size() {
      var q = Math.min(devicePixelRatio || 1, 1.5) * 0.6;
      canvas.width = Math.max(2, Math.floor(innerWidth * q));
      canvas.height = Math.max(2, Math.floor(innerHeight * q));
      gl.viewport(0, 0, canvas.width, canvas.height);
      gl.uniform2f(uR, canvas.width, canvas.height);
    }
    addEventListener("resize", size);
    size();

    function draw(ms) { gl.uniform1f(uT, ms * 0.001); gl.drawArrays(gl.TRIANGLES, 0, 3); }

    if (still) { draw(0); return; }
    var last = 0, step = 1000 / 30;
    (function loop(now) {
      if (lost) return;
      requestAnimationFrame(loop);
      if (now - last < step) return;
      last = now;
      draw(now);
    })(0);
  })();

  /* --- the line --------------------------------------------------------
     Guarded on its own elements. This handler once ran on a page that had no
     line and threw on load, which took the panels down with it, so every
     lookup below is checked rather than assumed.

     The <b> inside the code element is markup, so the text has to come from
     textContent rather than innerHTML or people paste a copy with tags in it.
  --------------------------------------------------------------------- */
  var line = document.getElementById("line");
  var run = document.getElementById("run");
  var copy = document.getElementById("copy");
  var copyText = document.getElementById("copyText");

  /* --- fitting the line ---------------------------------------------------
     The line is the one element on this page with a fixed amount it has to say,
     and on a phone there is not room to say it at 12.5px. Measured: it wants
     384 pixels and a 390 pixel phone has 322, so it overflowed on every handset
     width there is. It was scrolling sideways, which on a string somebody is
     meant to copy reads as broken rather than as scrollable.

     Fitted by measurement rather than by a vw clamp. A clamp has to be tuned to
     one exact string, and this string already changed once when the loader moved
     to the short form; the next change would have quietly broken it again. This
     asks the browser how wide the text actually is, which stays true whatever
     the string, the font fallback or the screen.
  --------------------------------------------------------------------- */
  function fitLine() {
    if (!run) return;
    // Cleared first, or each run measures the size the last run chose.
    run.style.fontSize = "";
    var full = parseFloat(getComputedStyle(run).fontSize);
    var size = full;
    // A tenth of a pixel at a time is pointless; a half is invisible and gets
    // there in a handful of passes.
    while (size > 8.5 && run.scrollWidth > run.clientWidth) {
      size -= 0.5;
      run.style.fontSize = size + "px";
    }
    // Nothing to do on a desktop, and leaving the attribute off keeps the
    // stylesheet in charge there.
    if (size >= full) run.style.fontSize = "";
  }

  fitLine();
  addEventListener("resize", fitLine);
  // Fonts land after first paint, and a monospace fallback is a different width
  // from SF Mono, so the first measurement can be of the wrong face.
  if (document.fonts && document.fonts.ready) document.fonts.ready.then(fitLine);

  if (line && run && copy) {
    var settle = null;
    copy.addEventListener("click", function () {
      var text = run.textContent;
      function done(ok) {
        line.classList.toggle("done", ok);
        if (copyText) copyText.textContent = ok ? "Copied" : "Press Ctrl+C";
        clearTimeout(settle);
        settle = setTimeout(function () {
          line.classList.remove("done");
          if (copyText) copyText.textContent = "Copy";
        }, 2000);
      }
      // The clipboard API needs a secure context and a permission that can be
      // refused. The selection fallback is not a nicety: without it the button
      // silently does nothing on exactly the browsers least likely to say why.
      if (navigator.clipboard && navigator.clipboard.writeText) {
        navigator.clipboard.writeText(text).then(function () { done(true); },
          function () { select(); });
      } else {
        select();
      }
      function select() {
        try {
          var range = document.createRange();
          range.selectNodeContents(run);
          var sel = window.getSelection();
          sel.removeAllRanges();
          sel.addRange(range);
          done(document.execCommand && document.execCommand("copy"));
        } catch (e) {
          done(false);
        }
      }
    });
  }

  /* --- the panels -------------------------------------------------------
     Nothing on this page scrolls, so anything that will not fit opens on top of
     it. Hidden is toggled as well as the class, so a closed panel is out of the
     tab order rather than merely invisible to look at.
  --------------------------------------------------------------------- */
  var scrim = document.getElementById("scrim");
  var panels = { menu: document.getElementById("p-menu") };
  var open = null, cameFrom = null;

  function shut() {
    if (!open) return;
    var p = panels[open];
    p.classList.remove("up");
    scrim.classList.remove("up");
    // Left until the fade has played, or it vanishes rather than closes.
    setTimeout(function () { if (!p.classList.contains("up")) p.hidden = true; }, 340);
    open = null;
    if (cameFrom) { cameFrom.focus(); cameFrom = null; }
  }

  function show(name, from) {
    if (open === name) return;
    if (open) {
      // Swapping panels rather than opening one: the old one goes without the
      // scrim flickering off and on between them.
      var was = panels[open];
      was.classList.remove("up");
      setTimeout(function () { if (!was.classList.contains("up")) was.hidden = true; }, 340);
    }
    var p = panels[name];
    p.hidden = false;
    // A frame between unhiding and the class, or the transition has nothing to
    // move from and the panel simply appears.
    requestAnimationFrame(function () {
      scrim.classList.add("up");
      p.classList.add("up");
    });
    open = name;
    if (from) cameFrom = from;
    var first = p.querySelector("[data-shut]");
    if (first) first.focus({ preventScroll: true });
  }

  document.addEventListener("click", function (e) {
    var opener = e.target.closest("[data-open]");
    if (opener) { show(opener.dataset.open, opener); return; }
    if (e.target.closest("[data-shut]")) { shut(); return; }
    if (e.target === scrim) shut();
  });
  addEventListener("keydown", function (e) { if (e.key === "Escape") shut(); });

  /* --- what is inside them ---------------------------------------------- */
  var tabs = [].slice.call(document.querySelectorAll(".tab"));
  var panes = [].slice.call(document.querySelectorAll(".pane"));
  tabs.forEach(function (t) {
    t.addEventListener("click", function () {
      tabs.forEach(function (o) { o.setAttribute("aria-selected", String(o === t)); });
      panes.forEach(function (p) {
        if (p.dataset.pane !== t.dataset.tab) { p.removeAttribute("data-live"); return; }
        // Cleared and re-set so the entrance replays. Left alone, the second
        // visit to a tab arrives with no animation, which reads as stuck.
        p.removeAttribute("data-live");
        void p.offsetWidth;
        p.setAttribute("data-live", "");
      });
    });
  });

  document.querySelectorAll(".sw").forEach(function (sw) {
    if (sw.tabIndex === -1) return;
    sw.addEventListener("click", function () {
      sw.setAttribute("aria-pressed", sw.getAttribute("aria-pressed") === "true" ? "false" : "true");
    });
  });

  var swatches = [].slice.call(document.querySelectorAll(".swatch"));
  swatches.forEach(function (s) {
    s.addEventListener("click", function () {
      swatches.forEach(function (o) { o.setAttribute("aria-pressed", String(o === s)); });
    });
  });

  // Pointer events rather than mouse events, so a finger works. The capture is
  // what keeps a drag alive once it leaves a bar six pixels tall, which on a
  // track this thin is most of them.
  document.querySelectorAll("[data-slider]").forEach(function (sld) {
    var bar = sld.querySelector(".sld-bar");
    var fill = sld.querySelector(".sld-fill");
    var knob = sld.querySelector(".sld-knob");
    var out = sld.querySelector("[data-out]");
    var min = +sld.dataset.min, max = +sld.dataset.max, value = +sld.dataset.value;

    function paint() {
      var a = (value - min) / (max - min);
      fill.style.width = (a * 100) + "%";
      knob.style.left = (a * 100) + "%";
      out.textContent = value;
    }
    function at(e) {
      var box = bar.getBoundingClientRect();
      var a = Math.min(1, Math.max(0, (e.clientX - box.left) / box.width));
      value = Math.round(min + (max - min) * a);
      paint();
    }
    bar.addEventListener("pointerdown", function (e) { bar.setPointerCapture(e.pointerId); at(e); });
    bar.addEventListener("pointermove", function (e) { if (bar.hasPointerCapture(e.pointerId)) at(e); });
    paint();
  });
})();
