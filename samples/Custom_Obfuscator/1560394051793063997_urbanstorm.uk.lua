      <div class="faq">
        <details class="reveal">
          <summary>Is Project Stark really free?</summary>
          <div class="faq-body">Yes. Free keys give you 4 hours of access to every game and refresh with one quick ad checkpoint. If you'd rather skip the checkpoints entirely, lifetime is a one-time $10 (or 2000 Robux).</div>
        </details>
        <details class="reveal" style="--d:60ms">
          <summary>How does the key system work?</summary>
          <div class="faq-body">Every user gets their own key. It locks to your PC — free keys run <b>1 Roblox account</b>, server boosters run <b>2</b>, and lifetime keys run <b>unlimited</b> accounts on that machine. Switching computers? Run <b>/hubreset</b> in the Discord — you can do that once every 7 days.</div>
        </details>
        <details class="reveal" style="--d:120ms">
          <summary>Which executors work?</summary>
          <div class="faq-body">Anything that supports HTTP requests — Potassium, Solara, Delta and similar. The loader fetches everything fresh each run, so there's nothing to download or update by hand.</div>
        </details>
        <details class="reveal" style="--d:180ms">
          <summary>Are the scripts safe to use?</summary>
          <div class="faq-body">Yes. Scripts are encrypted at rest and only served to verified keys, with watermarking and alt-account checks. Everything is fetched fresh by the loader — nothing is published or dumped.</div>
        </details>
        <details class="reveal" style="--d:240ms">
          <summary>The checkpoint won't complete — what do I do?</summary>
          <div class="faq-body">Join the <a href="/discord" target="_blank" rel="noopener noreferrer">Discord</a> and open a support ticket — staff will sort it out quickly.</div>
